        <p>Horses change barns, trainers and owners many times. Papers go missing, vet records stay in a clinic's files, show results sit in different associations' databases, and much of what people know about a horse lives in memory. When someone needs to know the horse, they get pieces.</p>
        <p>Horsefax keeps a lasting record of a horse's identity and history, with evidence and attribution, from foaling to retirement. It belongs with the horse, and its owner decides what is shared.</p>
        <h2>What we believe</h2>
        <ul>
            <li><strong>Evidence over claims.</strong> Every fact says how it is known.</li>
            <li><strong>Owners control access.</strong> Records start private; sharing is deliberate and can be revoked.</li>
            <li><strong>No silent edits.</strong> Corrections add to the history rather than erase it, and every change is logged.</li>
            <li><strong>Honesty about gaps.</strong> A missing record is never treated as proof that nothing happened.</li>
        </ul>
