        <h2>Information we collect</h2>
        <ul>
            <li><strong>Account information:</strong> your name, email address and password (stored only as a secure hash), and, if you turn it on, two-factor sign-in settings.</li>
            <li><strong>Horse records you add:</strong> identity details, identifiers such as registration and microchip numbers, pedigree, history entries (health, care, training, competition, ownership, sales, transport), photos, videos, documents and media releases.</li>
            <li><strong>Submissions:</strong> ownership claims, correction requests and contact messages, including the name and email you give us.</li>
            <li><strong>Technical information:</strong> IP address, browser details and the date and time of requests, used for security, abuse prevention and our audit trail. We use cookies that are needed to keep you signed in and protect forms; we do not use advertising cookies.</li>
        </ul>

        <h2>How we use information</h2>
        <ul>
            <li>To provide the Service: keep horse records, show them to the people you choose, and process claims, transfers and corrections.</li>
            <li>To keep records trustworthy: detect duplicate identifiers, review disputes, and keep an audit trail of changes.</li>
            <li>To protect the Service and its users from fraud, abuse and security threats.</li>
            <li>To communicate with you about your account and records.</li>
        </ul>
        <p>We do not sell your personal information.</p>

        <h2>What other people can see</h2>
        <ul>
            <li>Records are <strong>private by default</strong>. Only you, other people you make stewards of the record, and Horsefax staff can see private items.</li>
            <li>If you turn on a <strong>public summary</strong>, items you mark Public appear on it and in Horsefax search.</li>
            <li>If you create a <strong>report link</strong>, anyone with the link can see the items marked Shared or Public in the sections you chose, until the link expires or you revoke it.</li>
            <li>Public summaries and reports never show your name, email, address or other contact details, the identities of previous owners, or your original document files. Microchip numbers are masked.</li>
        </ul>

        <h2>When we share information</h2>
        <ul>
            <li><strong>Service providers</strong> who host, store, secure or send email for the Service, under obligations to protect it.</li>
            <li><strong>During a review:</strong> when an ownership claim or dispute involves a horse, we may tell the current owner that a review is under way, without disclosing the other person's private evidence or contact details unless they agree.</li>
            <li><strong>Legal reasons:</strong> when required by law, or to protect the rights, safety or property of Horsefax, our users or others.</li>
            <li><strong>Business transfers:</strong> if Horsefax is involved in a merger, acquisition or sale of assets, subject to this policy.</li>
        </ul>
        <p>Horsefax does not automatically share private records with any other company, including affiliated businesses. Any future integration will require the owner's authorization.</p>

        <h2>Retention</h2>
        <p>Horse records are designed to last for the horse's lifetime, and the audit trail is append-only. If you close your account, we stop showing your personal details, and you may ask us to remove items you contributed that are not needed to keep the record accurate. We keep some information when the law requires it, to resolve disputes, or to keep the record's history intact.</p>

        <h2>Your choices and rights</h2>
        <ul>
            <li>Change the visibility of any item, turn your public summary off, and revoke report links at any time.</li>
            <li>Ask for a copy of your personal information, or for corrections or deletion, through the contact form. Depending on where you live, you may have additional rights under local law, and we will honor them as required.</li>
        </ul>

        <h2>Security</h2>
        <p>We use encrypted connections, hashed passwords, access controls, rate limits, and an append-only audit log. Staff access requires two-factor sign-in. No system is perfectly secure, so please use a strong, unique password.</p>

        <h2>Children</h2>
        <p>The Service is not intended for anyone under 18, and we do not knowingly collect information from children.</p>

        <h2>Changes</h2>
        <p>We will post changes to this policy here and update the date above. If a change is significant, we will tell signed-in users.</p>
