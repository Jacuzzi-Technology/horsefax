        <h2 class="!mt-0">Request a correction</h2>
        <p>On any public summary or report, use <strong>Request a correction</strong>. Tell us which entry is wrong and how you know. Owners can correct their own entries directly from their record.</p>
        <h2>What happens next</h2>
        <ol>
            <li>Horsefax staff review the request and any evidence. Nothing changes on the record while it is reviewed.</li>
            <li>If the challenge is upheld, the entry is labeled <strong>Disputed</strong>. It is not deleted.</li>
            <li>The owner can then add a correction, which supersedes the entry. The original stays in the record's history.</li>
            <li>If the request is not upheld, the record stays as it is. Every decision is logged with the reason.</li>
        </ol>
        <h2>Ownership disputes</h2>
        <p>A person who believes they own a horse already on Horsefax can submit an ownership claim with evidence. Claims are reviewed by staff and never displace a current owner automatically.</p>
